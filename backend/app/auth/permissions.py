from __future__ import annotations

from enum import StrEnum


# ============================================================================
# Permissions
# ============================================================================


class Permission(StrEnum):
    """
    SentinelSIEM authorization permissions.

    Permission naming convention:

        <resource>:<action>

    Examples:

        events:read
        alerts:manage
        users:manage

    Audit access intentionally does not have a dedicated permission.
    Audit access is controlled through the existing users:read permission.
    """

    # ------------------------------------------------------------------------
    # Events
    # ------------------------------------------------------------------------

    EVENTS_READ = "events:read"

    # ------------------------------------------------------------------------
    # Alerts
    # ------------------------------------------------------------------------

    ALERTS_READ = "alerts:read"
    ALERTS_MANAGE = "alerts:manage"

    # ------------------------------------------------------------------------
    # Incidents
    # ------------------------------------------------------------------------

    INCIDENTS_READ = "incidents:read"
    INCIDENTS_MANAGE = "incidents:manage"

    # ------------------------------------------------------------------------
    # IOC
    # ------------------------------------------------------------------------

    IOCS_READ = "iocs:read"
    IOCS_MANAGE = "iocs:manage"

    # ------------------------------------------------------------------------
    # MITRE
    # ------------------------------------------------------------------------

    MITRE_READ = "mitre:read"

    # ------------------------------------------------------------------------
    # Dashboard
    # ------------------------------------------------------------------------

    DASHBOARD_READ = "dashboard:read"

    # ------------------------------------------------------------------------
    # User Management
    # ------------------------------------------------------------------------

    USERS_READ = "users:read"
    USERS_MANAGE = "users:manage"

    # ------------------------------------------------------------------------
    # Role Management
    # ------------------------------------------------------------------------

    ROLES_READ = "roles:read"
    ROLES_MANAGE = "roles:manage"

    # ------------------------------------------------------------------------
    # Detection
    # ------------------------------------------------------------------------

    DETECTIONS_READ = "detections:read"
    DETECTIONS_MANAGE = "detections:manage"

    # ------------------------------------------------------------------------
    # Assets
    # ------------------------------------------------------------------------

    ASSETS_READ = "assets:read"
    ASSETS_MANAGE = "assets:manage"

    # ------------------------------------------------------------------------
    # System
    # ------------------------------------------------------------------------

    SYSTEM_READ = "system:read"


# ============================================================================
# Permission Registry
# ============================================================================


ALL_PERMISSIONS: frozenset[str] = frozenset(
    permission.value
    for permission in Permission
)


# ============================================================================
# Public Exports
# ============================================================================


__all__ = [
    "Permission",
    "ALL_PERMISSIONS",
]